/**
 * Multi-Format Intelligence Report Generator
 * Generates exportable investigation reports in Markdown, JSON, CSV,
 * and standalone printable HTML (with print-to-PDF support).
 */

export interface ReportData {
  id: number | string;
  queryType: string;
  queryValue: string;
  createdAt: string;
  entities: {
    names?: string[];
    profile_pictures?: string[];
    banners?: string[];
    usernames?: string[];
    emails?: string[];
    phones?: string[];
    first_seen?: string;
    last_seen?: string;
  };
  summary: {
    total: number;
    candidates: number;
    providers: number;
  };
  threatMatrix: {
    overall_threat_score: number;
    risk_level: string;
    categories?: Record<string, { score: number; label: string }>;
  };
  evidence: {
    provider: string;
    category?: string | null;
    profile_url?: string | null;
    domain?: string | null;
    status: string;
    identity_name?: string | null;
    identifier_display?: string | null;
    fields_count?: number;
    extra_fields?: Record<string, string>;
    detail?: string | null;
    confidence?: string | null;
    checked_at?: string;
  }[];
  ai?: {
    executiveSummary?: string;
    threatLevel?: string;
    threatScore?: number;
    keyFindings?: string[];
    timeline?: { date: string; title: string; description: string; source: string; category: string }[];
    recommendedPivots?: { query: string; type: string; reason: string; priority: string }[];
    anomalyFlags?: string[];
  };
}

export function generateMarkdownReport(data: ReportData): string {
  const candidates = data.evidence.filter(e => e.status === "candidate");
  const observations = data.evidence.filter(e => e.status === "observed");
  const names = (data.entities.names || []).join(", ") || "—";
  const phones = (data.entities.phones || []).join(", ") || "—";
  const emails = (data.entities.emails || []).join(", ") || "—";
  const usernames = (data.entities.usernames || []).join(", ") || "—";

  return `# ShadowTrace OSINT Intelligence Report
**Investigation Target:** \`${data.queryValue}\`  
**Target Type:** ${data.queryType.toUpperCase()}  
**Investigation ID:** \`${data.id}\`  
**Generated At:** ${data.createdAt}  
**Classification:** TLP:CLEAR / OPEN-SOURCE INTELLIGENCE  

---

## 1. Executive Summary
${data.ai?.executiveSummary || `Automated OSINT investigation identified ${candidates.length} candidate platform accounts across ${data.summary.total} evaluated sources. Overall assessed threat score is ${data.threatMatrix.overall_threat_score}/100 (${data.threatMatrix.risk_level}).`}

---

## 2. Discovered Entities & Identifiers
| Field | Discovered Values |
|---|---|
| **Discovered Names** | ${names} |
| **Known Handles** | ${usernames} |
| **Linked Phones** | ${phones} |
| **Linked Emails** | ${emails} |
| **First Sighted** | ${data.entities.first_seen || '—'} |
| **Last Sighted** | ${data.entities.last_seen || '—'} |

---

## 3. Threat Assessment Matrix
- **Overall Threat Score:** **${data.threatMatrix.risk_level === "unassessed" ? "Unassessed" : `${data.threatMatrix.overall_threat_score}/100`}**
- **Risk Level:** **${data.threatMatrix.risk_level.toUpperCase()}**
${data.ai?.anomalyFlags && data.ai.anomalyFlags.length > 0 ? `\n### Key Risk Indicators\n${data.ai.anomalyFlags.map(f => `- ⚠️ ${f}`).join("\n")}` : ""}

---

## 4. Chronological Intelligence Timeline
| Date | Milestone | Details | Source |
|---|---|---|---|
${(data.ai?.timeline || []).map(t => `| **${t.date}** | ${t.title} | ${t.description} | ${t.source} |`).join("\n")}

---

## 5. Candidate Evidence & Platform Footprints (${candidates.length})
| Provider | Category | Discovered Identity / Details | Confidence | Source URL |
|---|---|---|---|---|
${candidates.map(c => `| **${c.provider}** | ${c.category || 'Identity'} | ${c.identity_name ? `**${c.identity_name}** - ` : ''}${c.identifier_display || c.detail || 'Candidate profile'} | ${c.confidence || 'unknown'} candidate | [Open source](${c.profile_url || '#'}) |`).join("\n")}

## 6. Technical Observations (${observations.length})
| Provider | Observation | Collected at | Source URL |
|---|---|---|---|
${observations.map(o => `| **${o.provider}** | ${(o.detail || o.identifier_display || 'Observation').replace(/\|/g, '\\|')} | ${o.checked_at || '—'} | [Open source](${o.profile_url || '#'}) |`).join("\n")}

---

## 6. Recommended Next-Step Pivots
${(data.ai?.recommendedPivots || []).map(p => `- **[${p.priority.toUpperCase()}]** Pivot onto \`${p.query}\` (${p.type}): ${p.reason}`).join("\n")}

---
*Generated by ShadowTrace OSINT Platform. This report is not independently certified; source records require analyst review.*
`;
}

export function generateCSVReport(data: ReportData): string {
  const headers = ["Provider", "Category", "Status", "Confidence", "Identity Name", "Identifier / Detail", "Profile URL", "Fields Count", "Checked At"];
  const rows = data.evidence.map(e => [
    `"${(e.provider || "").replace(/"/g, '""')}"`,
    `"${(e.category || "").replace(/"/g, '""')}"`,
    `"${(e.status || "").replace(/"/g, '""')}"`,
    `"${(e.confidence || "").replace(/"/g, '""')}"`,
    `"${(e.identity_name || "").replace(/"/g, '""')}"`,
    `"${(e.identifier_display || e.detail || "").replace(/"/g, '""')}"`,
    `"${(e.profile_url || "").replace(/"/g, '""')}"`,
    e.fields_count || 1,
    `"${(e.checked_at || data.createdAt).replace(/"/g, '""')}"`
  ]);

  return [headers.join(","), ...rows.map(r => r.join(","))].join("\r\n");
}

